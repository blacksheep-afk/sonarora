from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent
ASSETS=ROOT/'composition'/'assets'/'screens';ASSETS.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
 browser=p.chromium.launch()
 page=browser.new_page(viewport={'width':1280,'height':800},device_scale_factor=1.5,reduced_motion='reduce')
 page.goto('http://127.0.0.1:5173/')
 page.get_by_role('heading',name='Your money',exact=True).wait_for()
 def capture(name,selector):
  page.locator(selector).screenshot(path=str(ASSETS/(name+'.png')))
  print(name,flush=True)
 capture('home-empty','.home-workspace');capture('form-empty','.input-panel')
 for key,value in [('cash','600'),('bank','0'),('receivable','300'),('receiptDay','2')]:page.locator('#'+key).fill(value)
 capture('form-partial','.input-panel')
 page.locator('#inputs').get_by_role('button',name='Use example',exact=True).click()
 page.locator('.result-highlight').wait_for()
 assert '6.25%' in page.locator('.result-panel').inner_text()
 capture('home-example','.home-workspace');capture('form-example','.input-panel');capture('result','.result-panel')
 page.locator('#inputs').get_by_role('button',name='Compare options',exact=True).click()
 page.locator('#comparison [data-strategy=now]').wait_for()
 capture('comparison','#comparison');capture('cards','.strategies')
 for key in ['now','wait','trigger']:capture('card-'+key,'[data-strategy='+key+']')
 page.locator('.comparison-map > summary').click()
 capture('money-map','.comparison-map')
 page.locator('.map-choices > summary').click()
 page.locator('#map-strategy').select_option('now')
 options=page.locator('#map-path option').evaluate_all('ns=>ns.map(n=>({v:n.value,t:n.textContent}))')
 match=next((x['v'] for x in options if 'does not arrive' in x['t'] and 'do not happen' in x['t']),options[-1]['v'])
 page.locator('#map-path').select_option(match)
 page.locator('.map-choices > summary').click()
 capture('money-path','.comparison-map')
 page.get_by_role('link',name='Check a purchase',exact=True).click()
 capture('purchase-page','#safe-to-buy')
 page.get_by_role('button',name='I understand and want to continue',exact=True).click()
 dialog=page.get_by_role('dialog',name='Check smaller purchases',exact=True);dialog.wait_for()
 capture('purchase-modal','.purchase-dialog')
 dialog.get_by_role('button',name='Check smaller purchases',exact=True).click()
 dialog.locator('[data-testid=safe-result] h3').first.wait_for()
 dialog.locator('.details-dialog-body').evaluate('n=>n.scrollTop=n.scrollHeight')
 capture('purchase-result','.purchase-dialog')
 dialog.locator('.details-dialog-body').evaluate('n=>n.scrollTop=0')
 page.locator('#minimumBatch').fill('wrong')
 dialog.get_by_role('button',name='Check smaller purchases',exact=True).click()
 dialog.locator('[role=alert]').wait_for()
 dialog.locator('.details-dialog-body').evaluate('n=>n.scrollTop=0')
 capture('friendly-error','.purchase-dialog')
 browser.close()
